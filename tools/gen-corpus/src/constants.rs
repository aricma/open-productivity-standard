//! The generator's fixed knowledge: the corpus interface it reads, the tree it
//! writes, and the header it puts on that tree.
//!
//! Each of these mirrors something outside this crate, so each says what it has
//! to stay in step with. What is *not* here is Rust syntax — `mod.rs`, `.rs`,
//! `"../"` — because those are the shape of the language, not a choice anyone
//! can make differently.

/// The corpus lives here, relative to the repository root, one directory per
/// specification version.
pub(crate) const SPECS_DIR: &str = "specs";

/// A version's formats are documented in `formats/<name>.md`, relative to the
/// version. The corpus is laid out by those names.
pub(crate) const FORMATS_DIR: &str = "formats";

/// A version's corpus lives in `tests/`, relative to the version.
pub(crate) const TESTS_DIR: &str = "tests";

/// A case states its contract in this file. Mirrors the case layout in
/// `specs/<version>/tests/README.md`.
pub(crate) const CLAIM_FILE: &str = "claim.txt";

/// A case's input is `given.<ext>`, where the extension names its format.
pub(crate) const GIVEN_PREFIX: &str = "given.";

/// A round-trip or transform case's expected output is `expectation.<ext>`.
pub(crate) const EXPECTATION_PREFIX: &str = "expectation.";

/// The generated tests live here, relative to the repository root. Mirrors the
/// `[[test]]` entry in `ops/Cargo.toml` and the profile the mask runs.
pub(crate) const ACCEPTANCE_DIR: &str = "ops/tests/acceptance";

/// Why a generated test is skipped: the format it needs is not one the
/// implementation claims. A skip stays visible and counted in the test output.
pub(crate) const UNSUPPORTED_REASON: &str = "unsupported format:";

/// The header of the generated `main.rs`, which is a module per version.
pub(crate) const ACCEPTANCE_HEADER: &str = "\
//! Runs the language-agnostic corpus in `specs/<version>/tests`, one
//! `#[test]` per case, grouped by format. Cases for a format this crate
//! does not claim are `#[ignore]`d, so skips stay visible and counted.
//!
//! Generated by `gen-corpus`; do not edit by hand.

";
